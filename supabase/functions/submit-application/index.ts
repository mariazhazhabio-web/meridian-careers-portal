// ════════════════════════════════════════════════════════════════════════════
// POST /functions/v1/submit-application   (multipart/form-data)
//
// The ONLY write path for public applicants. Pipeline:
//   1. Origin allow-list + method + payload-size guard
//   2. Spam protection: honeypot, minimum fill time, optional Cloudflare Turnstile
//   3. Rate limits: per salted-IP-hash (5/hour) and per email (3 open applications / 30 days)
//   4. Server-side validation (shared rules.js — identical to the browser)
//   5. Vacancy must exist AND be published
//   6. Resume: extension, declared MIME, size ≤ 5 MB, magic-byte signature
//   7. Upload to PRIVATE bucket with a random server-generated path
//   8. Insert application (reference generated by Postgres); rollback file on failure
//   9. Send applicant acknowledgement + HR notification (Resend), log both
// Deploy: supabase functions deploy submit-application --no-verify-jwt
// (anonymous visitors call it with the public anon key; no user JWT exists)
// ════════════════════════════════════════════════════════════════════════════
import { validateApplication, validateResumeMeta, signatureMatches, fileExtension, MIME_BY_EXT, MIN_FILL_SECONDS, UPLOAD } from '../_shared/rules.js';
import { applicantAcknowledgementEmail, hrNotificationEmail } from '../_shared/emailTemplates.js';
import { adminClient, clientIp, corsHeaders, json, originAllowed, sha256Hex } from '../_shared/http.ts';
import { sendAndLog } from '../_shared/mailer.ts';

const MAX_BODY = UPLOAD.maxBytes + 200_000; // file + form fields
const IP_LIMIT_PER_HOUR = 5;
const EMAIL_LIMIT_OPEN = 3;

async function verifyTurnstile(token: string, ip: string): Promise<boolean> {
  const secret = Deno.env.get('TURNSTILE_SECRET_KEY');
  if (!secret) return true; // not configured → skip
  if (!token) return false;
  const res = await fetch('https://challenges.cloudflare.com/turnstile/v0/siteverify', {
    method: 'POST',
    body: new URLSearchParams({ secret, response: token, remoteip: ip }),
  });
  const data = await res.json().catch(() => ({}));
  return data.success === true;
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders(req) });
  if (req.method !== 'POST') return json(req, { error: 'Method not allowed' }, 405);
  if (!originAllowed(req)) return json(req, { error: 'Origin not allowed' }, 403);

  const len = Number(req.headers.get('content-length') ?? 0);
  if (len > MAX_BODY) return json(req, { error: `Upload too large. Resume must be ${UPLOAD.maxLabel} or smaller.` }, 413);
  if (!(req.headers.get('content-type') ?? '').includes('multipart/form-data'))
    return json(req, { error: 'Expected multipart/form-data' }, 415);

  let form: FormData;
  try {
    form = await req.formData();
  } catch {
    return json(req, { error: 'Malformed form data' }, 400);
  }
  const field = (k: string) => (form.get(k) ?? '').toString();

  // ── 2. Spam protection ──
  if (field('website')) return json(req, { error: 'Submission rejected.' }, 400); // honeypot
  const startedAt = Number(field('startedAt'));
  if (!startedAt || (Date.now() - startedAt) / 1000 < MIN_FILL_SECONDS)
    return json(req, { error: 'That was quick! Please review your details and submit again.' }, 429);

  const ip = clientIp(req);
  if (!(await verifyTurnstile(field('turnstileToken'), ip)))
    return json(req, { error: 'Spam check failed. Please refresh the page and try again.' }, 403);

  const db = adminClient();
  const ipHash = await sha256Hex(`${Deno.env.get('IP_HASH_SALT') ?? 'meridian'}:${ip}`);

  // ── 3. Rate limits ──
  const hourAgo = new Date(Date.now() - 3600e3).toISOString();
  const { count: ipCount } = await db.from('applications').select('id', { count: 'exact', head: true }).eq('ip_hash', ipHash).gte('created_at', hourAgo);
  if ((ipCount ?? 0) >= IP_LIMIT_PER_HOUR) return json(req, { error: 'Too many applications from this network. Please try again later.' }, 429);

  // ── 4. Validation ──
  const jobId = field('jobId');
  const { data: job } = await db.from('jobs').select('id, title, department, status').eq('id', jobId).maybeSingle();
  const { valid, errors, values } = validateApplication(
    {
      fullName: field('fullName'),
      email: field('email'),
      phone: field('phone'),
      jobId,
      experience: field('experience'),
      coverLetter: field('coverLetter'),
      consent: field('consent'),
    },
    { jobIds: job && job.status === 'published' ? [job.id] : [] },
  );

  // ── 6. File checks ──
  const file = form.get('resume');
  let bytes: Uint8Array | null = null;
  if (!(file instanceof File)) {
    errors.resume = 'Please upload your resume (PDF, DOC or DOCX).';
  } else {
    const metaErr = validateResumeMeta({ name: file.name, type: file.type, size: file.size });
    if (metaErr) errors.resume = metaErr;
    else {
      bytes = new Uint8Array(await file.arrayBuffer());
      if (!signatureMatches(bytes, fileExtension(file.name))) errors.resume = 'This file does not look like a genuine PDF or Word document.';
    }
  }
  if (!valid || errors.resume) return json(req, { error: 'Please correct the highlighted fields.', fieldErrors: errors }, 422);

  const thirtyDaysAgo = new Date(Date.now() - 30 * 86400e3).toISOString();
  const { count: emailCount } = await db
    .from('applications')
    .select('id', { count: 'exact', head: true })
    .eq('email', values.email)
    .in('status', ['new', 'shortlisted', 'interviewed'])
    .gte('created_at', thirtyDaysAgo);
  if ((emailCount ?? 0) >= EMAIL_LIMIT_OPEN)
    return json(req, { error: `You already have ${EMAIL_LIMIT_OPEN} applications in progress. Please wait for an update before applying again.` }, 429);

  // ── 7. Private upload (server-generated path, server-determined content type) ──
  const f = file as File;
  const ext = fileExtension(f.name);
  const path = `${job!.id}/${crypto.randomUUID()}.${ext}`;
  const safeName = f.name.replace(/[^\w.\- ]+/g, '_').slice(0, 200);
  const up = await db.storage.from('resumes').upload(path, bytes!, { contentType: MIME_BY_EXT[ext as keyof typeof MIME_BY_EXT], upsert: false });
  if (up.error) return json(req, { error: 'Could not store your resume. Please try again.' }, 500);

  // ── 8. Insert ──
  const { data: app, error: insErr } = await db
    .from('applications')
    .insert({
      job_id: job!.id,
      full_name: values.fullName,
      email: values.email,
      phone: values.phone,
      experience: values.experience,
      cover_letter: values.coverLetter,
      consent: true,
      resume_path: path,
      resume_name: safeName,
      resume_size: f.size,
      resume_type: MIME_BY_EXT[ext as keyof typeof MIME_BY_EXT],
      ip_hash: ipHash,
    })
    .select('id, reference, created_at')
    .single();

  if (insErr) {
    await db.storage.from('resumes').remove([path]);
    if (insErr.code === '23505') return json(req, { error: 'You have already applied for this role. Please contact HR if you need to update your application.' }, 409);
    console.error('insert failed', insErr);
    return json(req, { error: 'Submission failed. Please try again.' }, 500);
  }

  // ── 9. Emails (never block the applicant on email failures) ──
  const ctx = { ...values, reference: app.reference, createdAt: app.created_at, jobTitle: job!.title, department: job!.department };
  const site = Deno.env.get('SITE_URL') ?? '';
  await Promise.allSettled([
    sendAndLog(db, applicantAcknowledgementEmail(ctx), { applicationId: app.id, reference: app.reference }),
    sendAndLog(
      db,
      hrNotificationEmail({ ...ctx, hrEmail: Deno.env.get('HR_NOTIFY_EMAIL') ?? 'talent@example.com', dashboardUrl: `${site}/#/admin/applications/${app.id}` }),
      { applicationId: app.id, reference: app.reference },
    ),
  ]);

  return json(req, { reference: app.reference, createdAt: app.created_at, jobTitle: job!.title, email: values.email }, 201);
});
